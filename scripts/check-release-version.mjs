import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const json = p => JSON.parse(readFileSync(p, 'utf8'));
const version = json('package.json').version;
assert.match(version, /^\d+\.\d+\.\d+$/);
assert.equal(json('package-lock.json').version, version);
assert.equal(json('package-lock.json').packages[''].version, version);
assert.equal(json('src-tauri/tauri.conf.json').version, version);
const cargo = readFileSync('src-tauri/Cargo.toml', 'utf8');
assert.equal(cargo.match(/\[package\][\s\S]*?\nversion = "([^"]+)"/)[1], version);
const lock = readFileSync('src-tauri/Cargo.lock', 'utf8');
assert.equal(lock.match(/name = "universal-creative-software-hub"\nversion = "([^"]+)"/)[1], version);
if (process.env.RELEASE_TAG) assert.equal(process.env.RELEASE_TAG, `v${version}`);
console.log(`Release version verified: v${version}`);
